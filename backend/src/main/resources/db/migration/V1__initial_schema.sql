-- =============================================================
-- nasFinance - schema inicial
-- =============================================================
-- Decisoes de modelagem:
--
-- 1) Valores em NUMERIC(14,2), nunca em float/double. Ponto flutuante
--    binario nao representa 0.10 exatamente e acumula erro de centavo
--    em somatorios. No Java isso vira BigDecimal.
--
-- 2) `amount` e sempre POSITIVO. O sinal vem da coluna `flow`
--    (EXPENSE / INCOME). Isso evita a ambiguidade de "gasto negativo"
--    e deixa as agregacoes explicitas (SUM com CASE).
--
-- 3) `occurred_on` e DATE, nao TIMESTAMP. Controle financeiro se importa
--    com o dia da compra, nao com o segundo. Usar DATE elimina toda a
--    classe de bugs de fuso horario em relatorios mensais (uma compra
--    as 22h de 31/01 em UTC-3 cairia em fevereiro se fosse TIMESTAMPTZ
--    agrupado em UTC).
-- =============================================================

-- -------------------------------------------------------------
-- accounts: de onde o dinheiro sai ou para onde entra
-- -------------------------------------------------------------
CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80)     NOT NULL,
    kind            VARCHAR(20)     NOT NULL,
    color           VARCHAR(7)      NOT NULL DEFAULT '#64748B',
    opening_balance NUMERIC(14,2)   NOT NULL DEFAULT 0,
    archived        BOOLEAN         NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CONSTRAINT uq_accounts_name UNIQUE (name),
    CONSTRAINT ck_accounts_kind CHECK (kind IN
        ('CHECKING', 'SAVINGS', 'CREDIT_CARD', 'MEAL_VOUCHER', 'CASH', 'INVESTMENT', 'OTHER'))
);

COMMENT ON TABLE  accounts IS 'Contas / origens de dinheiro (corrente, vale refeicao, cartao, especie)';
COMMENT ON COLUMN accounts.opening_balance IS 'Saldo inicial ao cadastrar a conta; o saldo atual e calculado somando as transacoes';

-- -------------------------------------------------------------
-- categories: classificacao do gasto ou da receita
-- -------------------------------------------------------------
CREATE TABLE categories (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(60)     NOT NULL,
    flow           VARCHAR(10)     NOT NULL,
    color          VARCHAR(7)      NOT NULL DEFAULT '#64748B',
    icon           VARCHAR(40),
    monthly_budget NUMERIC(14,2),
    archived       BOOLEAN         NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CONSTRAINT uq_categories_name_flow UNIQUE (name, flow),
    CONSTRAINT ck_categories_flow CHECK (flow IN ('EXPENSE', 'INCOME')),
    CONSTRAINT ck_categories_budget CHECK (monthly_budget IS NULL OR monthly_budget >= 0)
);

COMMENT ON COLUMN categories.monthly_budget IS 'Teto mensal opcional; alimenta os alertas de orcamento no dashboard';

-- -------------------------------------------------------------
-- transactions: o registro central
-- -------------------------------------------------------------
CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT          NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    category_id BIGINT          REFERENCES categories(id) ON DELETE SET NULL,
    flow        VARCHAR(10)     NOT NULL,
    amount      NUMERIC(14,2)   NOT NULL,
    description VARCHAR(200),
    occurred_on DATE            NOT NULL,
    source      VARCHAR(20)     NOT NULL DEFAULT 'MANUAL',
    external_id VARCHAR(120),
    notes       TEXT,
    created_at  TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CONSTRAINT ck_transactions_flow CHECK (flow IN ('EXPENSE', 'INCOME')),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_transactions_source CHECK (source IN
        ('MANUAL', 'SHORTCUT', 'IMPORT', 'AGGREGATOR'))
);

COMMENT ON COLUMN transactions.external_id IS 'ID da transacao no sistema de origem (ex.: agregador Open Finance). Usado para deduplicar reenvios de webhook';
COMMENT ON COLUMN transactions.source IS 'Como a transacao entrou no sistema: MANUAL (web), SHORTCUT (iPhone), IMPORT (CSV), AGGREGATOR (webhook bancario)';

-- Deduplicacao: a mesma transacao externa nunca entra duas vezes.
-- Indice PARCIAL: so vale quando external_id existe, entao lancamentos
-- manuais (external_id NULL) nao colidem entre si.
CREATE UNIQUE INDEX uq_transactions_source_external
    ON transactions (source, external_id)
    WHERE external_id IS NOT NULL;

-- Indices para as consultas mais frequentes do dashboard
CREATE INDEX idx_transactions_occurred_on ON transactions (occurred_on DESC);
CREATE INDEX idx_transactions_account     ON transactions (account_id);
CREATE INDEX idx_transactions_category    ON transactions (category_id);
-- Cobre o filtro "gastos do mes corrente agrupados por categoria"
CREATE INDEX idx_transactions_flow_date   ON transactions (flow, occurred_on DESC);
