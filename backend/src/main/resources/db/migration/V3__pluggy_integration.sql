-- -------------------------------------------------------------
-- pluggy_account_links: qual conta da Pluggy e qual conta daqui
-- -------------------------------------------------------------
-- Sem este vinculo a sincronizacao nao tem onde gravar. A Pluggy
-- devolve, por exemplo, "PICPAY INSTITUICAO DE PAGAMENTO S.A" — e
-- cabe ao dono dizer que aquilo e a "Conta Corrente" dele.
--
-- O vinculo e explicito e nao adivinhado por tipo: o mesmo banco pode
-- expor duas contas corrente, e casar por heuristica colocaria
-- lancamentos na conta errada em silencio.
CREATE TABLE pluggy_account_links (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- UUID da conta no lado da Pluggy. UNIQUE: uma conta da Pluggy
    -- aponta para no maximo uma conta daqui. O caminho inverso tambem
    -- e 1:1 na pratica, mas nao e travado — duas contas da Pluggy
    -- apontando para a mesma conta local e estranho, nao corrompido.
    pluggy_account_id   VARCHAR(64)  NOT NULL UNIQUE,

    account_id          BIGINT       NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,

    -- Copia do nome e do tipo no momento do vinculo, so para exibir na
    -- tela de configuracao sem precisar chamar a API da Pluggy a cada
    -- carregamento.
    pluggy_name         VARCHAR(160) NOT NULL,
    pluggy_type         VARCHAR(20)  NOT NULL,

    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_pluggy_links_type CHECK (pluggy_type IN ('BANK', 'CREDIT'))
);

COMMENT ON TABLE pluggy_account_links IS
    'Mapeia cada conta da Pluggy para uma conta local. Sem isso a sincronizacao nao sabe onde gravar';
COMMENT ON COLUMN pluggy_account_links.pluggy_type IS
    'BANK (corrente/poupanca) ou CREDIT (cartao). Determina o tratamento de pagamento de fatura';

CREATE INDEX idx_pluggy_links_account ON pluggy_account_links (account_id);


-- -------------------------------------------------------------
-- pluggy_sync_runs: historico de execucoes
-- -------------------------------------------------------------
-- Um job noturno que parou de rodar e o tipo de falha que passa meses
-- sem ser notada — a mesma licao do backup, que so virou backup de
-- verdade quando ganhou log e codigo de saida.
--
-- Com esta tabela, "a sincronizacao rodou essa noite?" se responde com
-- um SELECT, e nao garimpando log de container.
CREATE TABLE pluggy_sync_runs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    started_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at          TIMESTAMPTZ,

    -- lastUpdatedAt do item no momento da execucao. E o que permite
    -- pular trabalho: se nao mudou desde a ultima execucao bem
    -- sucedida, a Pluggy nao coletou nada novo e nao ha o que fazer.
    item_last_updated_at TIMESTAMPTZ,

    window_from          DATE,
    window_to            DATE,

    imported             INTEGER      NOT NULL DEFAULT 0,
    skipped              INTEGER      NOT NULL DEFAULT 0,
    flagged              INTEGER      NOT NULL DEFAULT 0,

    status               VARCHAR(20)  NOT NULL DEFAULT 'RUNNING',
    error                TEXT,

    CONSTRAINT ck_sync_runs_status CHECK (status IN
        ('RUNNING', 'SUCCESS', 'SKIPPED', 'FAILED'))
);

COMMENT ON COLUMN pluggy_sync_runs.status IS
    'SKIPPED = o item nao foi atualizado desde a ultima execucao; nao e erro';
COMMENT ON COLUMN pluggy_sync_runs.skipped IS
    'Descartados na importacao: abaixo do valor minimo, anteriores a data de corte, ou pagamento de fatura';

-- A consulta mais frequente e "qual foi a ultima execucao bem
-- sucedida?", feita no inicio de toda execucao.
CREATE INDEX idx_sync_runs_started ON pluggy_sync_runs (started_at DESC);


-- -------------------------------------------------------------
-- Fila de revisao
-- -------------------------------------------------------------
-- Transacao importada nem sempre pode entrar direto. "Sem categoria"
-- NAO ganha coluna propria: ja e derivavel de category_id IS NULL, e
-- duplicar esse estado criaria duas verdades que podem divergir.
--
-- O que precisa de coluna e o que nao da para derivar: a suspeita de
-- duplicata e a de transferencia.
ALTER TABLE transactions
    ADD COLUMN review_status VARCHAR(20) NOT NULL DEFAULT 'NONE',
    ADD COLUMN review_reason VARCHAR(40),
    -- Aponta para o lancamento que ja existia (tipicamente vindo do
    -- Atalho) e que esta importacao talvez duplique. ON DELETE SET
    -- NULL: apagar o original nao pode levar junto a copia importada.
    ADD COLUMN duplicate_of_id BIGINT REFERENCES transactions(id) ON DELETE SET NULL;

ALTER TABLE transactions
    ADD CONSTRAINT ck_transactions_review_status CHECK (review_status IN
        ('NONE', 'PENDING', 'DISMISSED')),
    ADD CONSTRAINT ck_transactions_review_reason CHECK (review_reason IS NULL OR review_reason IN
        ('POSSIBLE_DUPLICATE', 'POSSIBLE_TRANSFER'));

COMMENT ON COLUMN transactions.review_status IS
    'PENDING = aguarda decisao do usuario; DISMISSED = ele avaliou e manteve como esta';
COMMENT ON COLUMN transactions.duplicate_of_id IS
    'Lancamento preexistente que esta importacao talvez duplique. Proposta, nunca fusao automatica';

-- Indice PARCIAL: a fila so olha o que esta pendente, e em um banco
-- onde a esmagadora maioria das linhas tem review_status = 'NONE' um
-- indice cheio seria quase todo desperdicio.
CREATE INDEX idx_transactions_review_pending
    ON transactions (occurred_on DESC)
    WHERE review_status = 'PENDING';
