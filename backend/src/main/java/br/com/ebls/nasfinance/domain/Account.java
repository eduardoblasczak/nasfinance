package br.com.ebls.nasfinance.domain;

import java.math.BigDecimal;
import java.time.OffsetDateTime;
import java.util.List;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;

/**
 * Uma conta / origem de dinheiro: conta corrente, vale refeicao, cartao...
 * <p>
 * <b>Sobre os campos publicos:</b> este e o padrao "active record" do Panache.
 * Parece estranho para quem vem de Java tradicional, mas o Quarkus reescreve o
 * bytecode em tempo de build, transformando cada acesso a campo em chamada de
 * getter/setter. O encapsulamento existe no bytecode final; o codigo-fonte so
 * fica livre do boilerplate.
 * <p>
 * Estender {@link PanacheEntityBase} (em vez de {@code PanacheEntity}) permite
 * declarar o {@code id} manualmente, o que aqui e necessario: a tabela usa
 * {@code GENERATED BY DEFAULT AS IDENTITY}, entao a estrategia precisa ser
 * {@link GenerationType#IDENTITY}. O {@code PanacheEntity} padrao usaria
 * SEQUENCE e nao encontraria a sequence esperada.
 */
@Entity
@Table(name = "accounts")
public class Account extends PanacheEntityBase {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    public Long id;

    @Column(nullable = false, unique = true, length = 80)
    public String name;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    public AccountKind kind;

    /** Cor em hexadecimal (#RRGGBB), usada nos graficos do dashboard. */
    @Column(nullable = false, length = 7)
    public String color = "#64748B";

    /**
     * Saldo no momento em que a conta foi cadastrada.
     * O saldo atual = openingBalance + soma das transacoes.
     */
    @Column(name = "opening_balance", nullable = false, precision = 14, scale = 2)
    public BigDecimal openingBalance = BigDecimal.ZERO;

    /** Conta arquivada some dos formularios mas preserva o historico. */
    @Column(nullable = false)
    public boolean archived = false;

    @Column(name = "created_at", nullable = false, updatable = false)
    public OffsetDateTime createdAt;

    @PrePersist
    void onCreate() {
        if (createdAt == null) {
            createdAt = OffsetDateTime.now();
        }
    }

    // ---------------------------------------------------------------
    // Consultas (metodos estaticos = estilo active record do Panache)
    // ---------------------------------------------------------------

    /** Contas ativas, ordenadas por nome, para preencher formularios. */
    public static List<Account> listActive() {
        return find("archived = false ORDER BY name").list();
    }

    /** Busca por nome exato: usado pelo endpoint do Atalho do iPhone. */
    public static Account findByName(String name) {
        return find("LOWER(name) = LOWER(?1)", name).firstResult();
    }
}
